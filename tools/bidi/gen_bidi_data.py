"""
Write xhtml2pdf/_bidi_data.py from the Unicode Character Database.

The bidirectional algorithm in xhtml2pdf/bidi.py needs two properties the
standard library's unicodedata does not carry: Bidi_Mirroring_Glyph, which
says what a mirrored character turns into in right-to-left text, and
Bidi_Paired_Bracket, which says which brackets pair up for rule N0. This
reads both from BidiMirroring.txt and BidiBrackets.txt and writes them out
as two dictionaries.

    python tools/bidi/gen_bidi_data.py [UCD_DIR]

UCD_DIR holds the two files; without it they are downloaded for the Unicode
version below. The output only changes when that version does.
"""

from __future__ import annotations

import sys
import urllib.request
from pathlib import Path

UNICODE_VERSION = "15.1.0"
BASE_URL = f"https://www.unicode.org/Public/{UNICODE_VERSION}/ucd/"
OUTPUT = Path(__file__).resolve().parents[2] / "xhtml2pdf" / "_bidi_data.py"


def read_ucd(name: str, ucd_dir: Path | None) -> list[list[str]]:
    """The data lines of a UCD file, split into stripped fields."""
    if ucd_dir is not None:
        text = (ucd_dir / name).read_text(encoding="utf-8")
    else:
        with urllib.request.urlopen(BASE_URL + name) as response:
            text = response.read().decode("utf-8")
    rows = []
    for line in text.splitlines():
        data = line.split("#", 1)[0].strip()
        if data:
            rows.append([field.strip() for field in data.split(";")])
    return rows


def escape(code: int) -> str:
    return f"\\u{code:04x}" if code <= 0xFFFF else f"\\U{code:08x}"


def format_dict(name: str, items: list[str]) -> list[str]:
    lines = [f"{name} = {{"]
    lines.extend(
        "    " + " ".join(items[start : start + 4]) for start in range(0, len(items), 4)
    )
    lines.append("}")
    return lines


def main() -> None:
    ucd_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else None
    mirrors = sorted(
        (int(a, 16), int(b, 16)) for a, b in read_ucd("BidiMirroring.txt", ucd_dir)
    )
    brackets = sorted(
        (int(a, 16), int(b, 16), kind)
        for a, b, kind in read_ucd("BidiBrackets.txt", ucd_dir)
    )
    out = [
        f'"""Bidi_Mirroring_Glyph and Bidi_Paired_Bracket, Unicode {UNICODE_VERSION}.',
        "",
        "Generated by tools/bidi/gen_bidi_data.py from BidiMirroring.txt and",
        "BidiBrackets.txt. Do not edit by hand.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        f'UNICODE_VERSION = "{UNICODE_VERSION}"',
        "",
        "#: Character -> the character drawn in its place at an odd level (rule L4).",
        *format_dict(
            "MIRRORS: dict[str, str]",
            [f'"{escape(a)}": "{escape(b)}",' for a, b in mirrors],
        ),
        "",
        "#: Opening bracket -> its closing bracket (rule N0).",
        *format_dict(
            "OPENING_BRACKETS: dict[int, int]",
            [f"0x{a:04X}: 0x{b:04X}," for a, b, kind in brackets if kind == "o"],
        ),
        "",
        "#: Closing bracket -> its opening bracket (rule N0).",
        *format_dict(
            "CLOSING_BRACKETS: dict[int, int]",
            [f"0x{a:04X}: 0x{b:04X}," for a, b, kind in brackets if kind == "c"],
        ),
        "",
    ]
    OUTPUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUTPUT}: {len(mirrors)} mirrors, {len(brackets)} brackets")


if __name__ == "__main__":
    main()
