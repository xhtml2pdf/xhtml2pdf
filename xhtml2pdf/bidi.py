"""
The Unicode Bidirectional Algorithm (UAX #9), for one line of text.

ReportLab draws a string left to right, glyph after glyph, so text that
mixes directions has to be handed over in visual order: get_display takes a
string in logical order -- the order it is typed and stored in -- and
returns it in the order it is drawn in, with brackets and other mirrored
characters swapped for their mirror images where they end up right to left.

Everything here follows the rule names of UAX #9, which is the
documentation for why each step does what it does. Bidi classes come from
unicodedata; the two properties it lacks, mirroring glyphs and paired
brackets, are in _bidi_data, generated by tools/bidi/gen_bidi_data.py.
tools/bidi/conformance.py runs the Unicode conformance suites against it.
"""

from __future__ import annotations

import re
from typing import TYPE_CHECKING
from unicodedata import bidirectional

from xhtml2pdf._bidi_data import CLOSING_BRACKETS, MIRRORS, OPENING_BRACKETS

if TYPE_CHECKING:
    from collections.abc import Sequence

__all__ = [
    "CONTROL_CHARS",
    "display_order",
    "get_display",
    "mirrored",
    "needs_bidi",
    "resolve_levels",
]

MAX_DEPTH = 125
_BRACKET_STACK_SIZE = 63

_STRONG_OR_NUMBER = {"L": "L", "R": "R", "EN": "R", "AN": "R"}
_ISOLATE_INITIATORS = frozenset(("LRI", "RLI", "FSI"))
_ISOLATE_CONTROLS = frozenset(("LRI", "RLI", "FSI", "PDI"))
_EMBEDDINGS = frozenset(("LRE", "RLE", "LRO", "RLO"))
#: Removed by rule X9: they leave no level and take no part in what follows.
_REMOVED = frozenset(("LRE", "RLE", "LRO", "RLO", "PDF", "BN"))
_EXPLICIT_OR_REMOVED = _REMOVED | _ISOLATE_CONTROLS
#: Neutral and isolate types, the ones rules N1 and N2 resolve.
_NEUTRALS = frozenset(("B", "S", "WS", "ON", "LRI", "RLI", "FSI", "PDI"))
#: The classes that leave a left-to-right paragraph unchanged when absent.
_REORDERING = frozenset(
    ("R", "AL", "AN", "LRE", "RLE", "LRO", "RLO", "PDF", "LRI", "RLI", "FSI", "PDI")
)
#: Characters that only steer the algorithm. They are invisible, and a font
#: rarely has a glyph for them, so they are left out of what is drawn. The
#: other format characters (zero-width joiners, soft hyphens) stay.
CONTROL_CHARS = frozenset(
    "\u202a\u202b\u202c\u202d\u202e\u2066\u2067\u2068\u2069\u200e\u200f\u061c"
)
#: Types that rule L1 resets when they trail a line or a separator.
_TRAILING_RESET = _REMOVED | {"WS", "LRI", "RLI", "FSI", "PDI"}
#: One letter per type left after the weak rules, so that the runs rules N1
#: to I2 work on can be found by a regular expression rather than a loop.
_CODE = {"L": "L", "R": "R", "EN": "E", "AN": "N", **dict.fromkeys(_NEUTRALS, "n")}
_NEUTRAL_RUN = re.compile(r"n+")
_NOT_R_RUN = re.compile(r"[^R]+")
_RAISED_RUN = re.compile(r"(R+)|([EN]+)")
_MIRRORED = re.compile("[" + "".join(map(re.escape, MIRRORS)) + "]")
_BRACKET = re.compile(
    "["
    + "".join(re.escape(chr(c)) for c in (*OPENING_BRACKETS, *CLOSING_BRACKETS))
    + "]"
)
#: U+2329/U+232A are canonically equivalent to U+3008/U+3009 and pair with
#: them (BD16).
_CANONICAL_BRACKETS = {0x2329: 0x3008, 0x232A: 0x3009}

#: Default Bidi_Class of unassigned code points, from DerivedBidiClass.txt.
#: unicodedata reports "" for them; outside these ranges the default is L.
_UNASSIGNED_DEFAULTS = (
    (0x0590, 0x05FF, "R"),
    (0x0600, 0x07BF, "AL"),
    (0x07C0, 0x085F, "R"),
    (0x0860, 0x08FF, "AL"),
    (0x20A0, 0x20CF, "ET"),
    (0xFB1D, 0xFB4F, "R"),
    (0xFB50, 0xFDCF, "AL"),
    (0xFDF0, 0xFDFF, "AL"),
    (0xFE70, 0xFEFF, "AL"),
    (0x10800, 0x10CFF, "R"),
    (0x10D00, 0x10D3F, "AL"),
    (0x10D40, 0x10EBF, "R"),
    (0x10EC0, 0x10EFF, "AL"),
    (0x10F00, 0x10F2F, "R"),
    (0x10F30, 0x10F6F, "AL"),
    (0x10F70, 0x10FFF, "R"),
    (0x1E800, 0x1EC6F, "R"),
    (0x1EC70, 0x1ECBF, "AL"),
    (0x1ECC0, 0x1ECFF, "R"),
    (0x1ED00, 0x1ED4F, "AL"),
    (0x1ED50, 0x1EDFF, "R"),
    (0x1EE00, 0x1EEFF, "AL"),
    (0x1EF00, 0x1EFFF, "R"),
)


def bidi_class(char: str) -> str:
    """The Bidi_Class of `char`, with the defaults for unassigned ones."""
    return bidirectional(char) or _unassigned_class(char)


def _bidi_classes(text: str) -> list[str]:
    types = list(map(bidirectional, text))
    if "" in types:
        types = [
            cls or _unassigned_class(c) for cls, c in zip(types, text, strict=True)
        ]
    return types


def _unassigned_class(char: str) -> str:
    code = ord(char)
    for start, end, default in _UNASSIGNED_DEFAULTS:
        if start <= code <= end:
            return default
    return "L"


#: Text that can come out in another order than it is stored in: the blocks
#: of the right-to-left scripts (which hold every R, AL and AN character)
#: and the controls that open a right-to-left or isolated run.
#: tests/test_bidi.py checks it against every code point.
_NEEDS_BIDI = re.compile(
    "["
    + "".join(
        f"{re.escape(chr(start))}-{re.escape(chr(end))}"
        for start, end, default in _UNASSIGNED_DEFAULTS
        if default in {"R", "AL"}
    )
    + "\u200f\u202a-\u202e\u2066-\u2069]"
)


def needs_bidi(text: str, base_dir: str | None = "L") -> bool:
    """Whether `text` in a paragraph of `base_dir` is drawn in another order."""
    return base_dir != "L" or _NEEDS_BIDI.search(text) is not None


def display_order(text: str, base_dir: str | None = "L") -> tuple[list[int], list[int]]:
    """
    The indices of `text` in the order they are drawn, and each one's level.

    The order is the visual one, left to right, with the whole of `text` as
    one line (rule L2). A character at an odd level is drawn as its mirror
    image (L4), and the bidi controls not at all; both are left to the
    caller, who may be laying out more than characters.
    """
    types = _bidi_classes(text)
    if base_dir == "L" and _REORDERING.isdisjoint(types):
        return list(range(len(text))), [0] * len(text)
    order: list[int] = []
    levels: list[int] = []
    for start, end in _paragraphs(types):
        para_types = types[start:end]
        resolved = resolve_levels(
            para_types, _paragraph_level(para_types, base_dir), text[start:end]
        )
        if None in resolved:
            # A character removed by X9 is drawn where it stands, at the level
            # of the one before it (UAX #9, 5.2).
            previous = resolved[0] if resolved[0] is not None else 0
            for index, level in enumerate(resolved):
                if level is None:
                    resolved[index] = previous
                else:
                    previous = level
        filled: list[int] = resolved  # type: ignore[assignment]
        order.extend(start + i for i in reorder(filled))
        levels.extend(filled)
    return order, levels


def mirrored(char: str, level: int) -> str:
    """`char` as drawn at `level`: its mirror image at an odd one (L4)."""
    return MIRRORS.get(char, char) if level & 1 else char


def get_display(text: str, base_dir: str | None = "L") -> str:
    """
    `text` in visual order: the order its characters are drawn in, left to
    right.

    `base_dir` is the direction of the paragraph, "L" or "R"; None takes it
    from the first strong character (rules P2 and P3). The whole of `text`
    is laid out as one line -- each paragraph separator in it starts a new
    paragraph with the same base direction -- and the bidi control
    characters are dropped from the result.
    """
    if not text:
        return text
    if base_dir == "L" and _REORDERING.isdisjoint(_bidi_classes(text)):
        return text
    order, levels = display_order(text, base_dir)
    source = list(text)
    # Rule L4: what sits at an odd level is drawn as its mirror image.
    for match in _MIRRORED.finditer(text):
        index = match.start()
        if levels[index] & 1:
            source[index] = MIRRORS[source[index]]
    chars = [source[i] for i in order]
    if not CONTROL_CHARS.isdisjoint(text):
        chars = [c for c in chars if c not in CONTROL_CHARS]
    return "".join(chars)


def _paragraphs(types: Sequence[str]) -> list[tuple[int, int]]:
    """(start, end) of each paragraph, the separator closing its own (P1)."""
    spans = []
    start = 0
    for index, cls in enumerate(types):
        if cls == "B":
            spans.append((start, index + 1))
            start = index + 1
    if start < len(types):
        spans.append((start, len(types)))
    return spans


def _paragraph_level(types: Sequence[str], base_dir: str | None) -> int:
    if base_dir == "R":
        return 1
    if base_dir == "L":
        return 0
    return _first_strong_level(types, 0, len(types), _matching_pdis(types))


def _first_strong_level(
    types: Sequence[str], start: int, end: int, matches: dict[int, int]
) -> int:
    """Rules P2 and P3: 1 if the first strong character is R or AL."""
    index = start
    while index < end:
        cls = types[index]
        if cls == "L":
            return 0
        if cls in {"R", "AL"}:
            return 1
        if cls in _ISOLATE_INITIATORS:
            if index not in matches:
                break
            index = matches[index]
        index += 1
    return 0


def _matching_pdis(types: Sequence[str]) -> dict[int, int]:
    """Isolate initiator index -> index of its matching PDI (BD9)."""
    matches = {}
    open_isolates: list[int] = []
    for index, cls in enumerate(types):
        if cls in _ISOLATE_INITIATORS:
            open_isolates.append(index)
        elif cls == "PDI" and open_isolates:
            matches[open_isolates.pop()] = index
        elif cls == "B":
            open_isolates.clear()
    return matches


def resolve_levels(
    types: Sequence[str], para_level: int, text: str | None = None
) -> list[int | None]:
    """
    The embedding level of each character of one paragraph, after rule L1.

    `types` are the Bidi_Class values; `text`, when given, is what they
    were read from and is only needed to pair brackets (rule N0). A
    character removed by rule X9 gets None.
    """
    types = list(types)
    original = tuple(types)
    if _EXPLICIT_OR_REMOVED.isdisjoint(original):
        # Nothing to embed, isolate or remove: the paragraph is one level run
        # and one isolating run sequence, which is most text.
        levels = [para_level] * len(types)
        direction = "R" if para_level & 1 else "L"
        if types:
            _resolve_sequence(
                (list(range(len(types))), direction, direction),
                types,
                levels,
                original,
                text,
            )
        _reset_whitespace(original, levels, para_level)
        return list(levels)
    matches = _matching_pdis(types)
    levels = _explicit_levels(types, para_level, matches)
    for sequence in _isolating_run_sequences(original, levels, matches, para_level):
        _resolve_sequence(sequence, types, levels, original, text)
    _reset_whitespace(original, levels, para_level)
    return [
        None if original[i] in _REMOVED else level for i, level in enumerate(levels)
    ]


def _explicit_levels(
    types: list[str], para_level: int, matches: dict[int, int]
) -> list[int]:
    """Rules X1 to X8. Overrides are applied to `types` in place."""
    n = len(types)
    levels = [para_level] * n
    # Each entry: (level, override or "", isolate)
    stack: list[tuple[int, str, bool]] = [(para_level, "", False)]
    overflow_isolates = overflow_embeddings = valid_isolates = 0
    for index in range(n):
        cls = types[index]
        level, override, _ = stack[-1]
        if cls in _EMBEDDINGS:
            levels[index] = level
            new_level = (level + 1) | 1 if cls in {"RLE", "RLO"} else (level + 2) & ~1
            if (
                new_level <= MAX_DEPTH
                and not overflow_isolates
                and not overflow_embeddings
            ):
                new_override = "R" if cls == "RLO" else "L" if cls == "LRO" else ""
                stack.append((new_level, new_override, False))
            elif not overflow_isolates:
                overflow_embeddings += 1
        elif cls in _ISOLATE_INITIATORS:
            levels[index] = level
            if override:
                types[index] = override
            if cls == "FSI":
                end = matches.get(index, n)
                rtl = _first_strong_level(types, index + 1, end, matches)
                cls = "RLI" if rtl else "LRI"
            new_level = (level + 1) | 1 if cls == "RLI" else (level + 2) & ~1
            if (
                new_level <= MAX_DEPTH
                and not overflow_isolates
                and not overflow_embeddings
            ):
                valid_isolates += 1
                stack.append((new_level, "", True))
            else:
                overflow_isolates += 1
        elif cls == "PDI":
            if overflow_isolates:
                overflow_isolates -= 1
            elif valid_isolates:
                overflow_embeddings = 0
                while not stack[-1][2]:
                    stack.pop()
                stack.pop()
                valid_isolates -= 1
            level, override, _ = stack[-1]
            levels[index] = level
            if override:
                types[index] = override
        elif cls == "PDF":
            levels[index] = level
            if overflow_isolates:
                pass
            elif overflow_embeddings:
                overflow_embeddings -= 1
            elif not stack[-1][2] and len(stack) >= 2:
                stack.pop()
        elif cls == "B":
            levels[index] = para_level
        else:
            levels[index] = level
            if override and cls != "BN":
                types[index] = override
    return levels


def _isolating_run_sequences(
    types: Sequence[str],
    levels: Sequence[int],
    matches: dict[int, int],
    para_level: int,
) -> list[tuple[list[int], str, str]]:
    """
    Rule X10: each sequence's character indices, with its sos and eos.

    `types` are the original classes: an isolate initiator under an override
    still links its runs together.
    """
    kept = [i for i, cls in enumerate(types) if cls not in _REMOVED]
    if not kept:
        return []
    # Level runs, as lists of indices into the paragraph.
    runs: list[list[int]] = [[kept[0]]]
    for index in kept[1:]:
        if levels[index] == levels[runs[-1][-1]]:
            runs[-1].append(index)
        else:
            runs.append([index])
    run_starting_at = {run[0]: run for run in runs}
    matched_pdis = set(matches.values())
    position = {index: k for k, index in enumerate(kept)}

    sequences = []
    for run in runs:
        if run[0] in matched_pdis and types[run[0]] == "PDI":
            continue
        chars = list(run)
        while types[chars[-1]] in _ISOLATE_INITIATORS and chars[-1] in matches:
            following = run_starting_at.get(matches[chars[-1]])
            if following is None:
                break
            chars.extend(following)
        level = levels[chars[0]]
        k = position[chars[0]]
        before = levels[kept[k - 1]] if k > 0 else para_level
        k = position[chars[-1]]
        if k + 1 < len(kept) and not (
            types[chars[-1]] in _ISOLATE_INITIATORS and chars[-1] not in matches
        ):
            after = levels[kept[k + 1]]
        else:
            after = para_level
        sos = "R" if max(level, before) & 1 else "L"
        eos = "R" if max(level, after) & 1 else "L"
        sequences.append((chars, sos, eos))
    return sequences


def _resolve_sequence(
    sequence: tuple[list[int], str, str],
    types: list[str],
    levels: list[int],
    original: Sequence[str],
    text: str | None,
) -> None:
    """Rules W1 to I2 over one isolating run sequence."""
    chars, sos, eos = sequence
    t = [types[i] for i in chars]
    n = len(t)
    level = levels[chars[0]]

    # Each rule below only rewrites types that are present, so a rule whose
    # types are absent is skipped; most text has no marks or separators.
    present = set(t)

    # W1: a non-spacing mark takes the type of what it follows.
    if "NSM" in present:
        for k in range(n):
            if t[k] == "NSM":
                if k == 0:
                    t[k] = sos
                elif t[k - 1] in _ISOLATE_CONTROLS:
                    t[k] = "ON"
                else:
                    t[k] = t[k - 1]
        present = set(t)
    # W2 and W3: European numbers after Arabic letters are Arabic numbers;
    # Arabic letters are then plain right-to-left.
    if "AL" in present:
        if "EN" in present:
            last_strong = sos
            for k in range(n):
                cls = t[k]
                if cls in {"L", "R", "AL"}:
                    last_strong = cls
                elif cls == "EN" and last_strong == "AL":
                    t[k] = "AN"
        t = ["R" if cls == "AL" else cls for cls in t]
    if not present.isdisjoint(("ES", "ET", "CS")):
        # W4: one separator between two numbers of the same kind joins them.
        for k in range(1, n - 1):
            cls = t[k]
            if cls == "ES" and t[k - 1] == "EN" and t[k + 1] == "EN":
                t[k] = "EN"
            elif cls == "CS" and t[k - 1] == t[k + 1] and t[k - 1] in {"EN", "AN"}:
                t[k] = t[k - 1]
        # W5: terminators next to a European number belong to it.
        k = 0
        while k < n:
            if t[k] != "ET":
                k += 1
                continue
            end = k
            while end < n and t[end] == "ET":
                end += 1
            if (k > 0 and t[k - 1] == "EN") or (end < n and t[end] == "EN"):
                t[k:end] = ["EN"] * (end - k)
            k = end
        # W6: separators and terminators left over are neutral.
        t = ["ON" if cls in {"ES", "ET", "CS"} else cls for cls in t]
    # W7: European numbers in left-to-right context are left-to-right.
    if "EN" in t:
        last_strong = sos
        for k in range(n):
            cls = t[k]
            if cls in {"L", "R"}:
                last_strong = cls
            elif cls == "EN" and last_strong == "L":
                t[k] = "L"

    embedding = "R" if level & 1 else "L"
    if text is not None and "ON" in t:
        _resolve_brackets(chars, t, original, text, sos, embedding)

    # N1 and N2: a run of neutrals between two strong types of the same
    # direction takes it; any other takes the embedding direction.
    for match in _NEUTRAL_RUN.finditer("".join(map(_CODE.__getitem__, t))):
        k, end = match.span()
        before = _STRONG_OR_NUMBER[t[k - 1]] if k > 0 else sos
        after = _STRONG_OR_NUMBER[t[end]] if end < n else eos
        t[k:end] = [before if before == after else embedding] * (end - k)

    # I1 and I2: what goes against the embedding direction is raised.
    code = "".join(map(_CODE.__getitem__, t))
    if level & 1:
        raised = [(m.span(), level + 1) for m in _NOT_R_RUN.finditer(code)]
    else:
        raised = [
            (m.span(), level + m.lastindex)  # type: ignore[operator]
            for m in _RAISED_RUN.finditer(code)
        ]
    offset = chars[0]
    contiguous = chars[-1] - offset + 1 == n
    for (k, end), value in raised:
        if contiguous:
            levels[offset + k : offset + end] = [value] * (end - k)
        else:
            for index in chars[k:end]:
                levels[index] = value


def _resolve_brackets(
    chars: list[int],
    t: list[str],
    original: Sequence[str],
    text: str,
    sos: str,
    embedding: str,
) -> None:
    """Rule N0: a bracket pair takes the direction of what it encloses."""
    offset = chars[0]
    if chars[-1] - offset + 1 == len(chars):
        candidates = [
            m.start() - offset for m in _BRACKET.finditer(text, offset, chars[-1] + 1)
        ]
    else:
        position = {index: k for k, index in enumerate(chars)}
        candidates = [
            position[m.start()]
            for m in _BRACKET.finditer(text)
            if m.start() in position
        ]
    pairs = []
    stack: list[tuple[int, int]] = []  # (closing bracket, position)
    for k in candidates:
        if t[k] != "ON":
            continue
        code = ord(text[chars[k]])
        if code in OPENING_BRACKETS:
            if len(stack) == _BRACKET_STACK_SIZE:
                break
            closing = OPENING_BRACKETS[code]
            stack.append((_CANONICAL_BRACKETS.get(closing, closing), k))
        elif code in CLOSING_BRACKETS:
            code = _CANONICAL_BRACKETS.get(code, code)
            for depth in range(len(stack) - 1, -1, -1):
                if stack[depth][0] == code:
                    pairs.append((stack[depth][1], k))
                    del stack[depth:]
                    break
    if not pairs:
        return
    pairs.sort()
    opposite = "L" if embedding == "R" else "R"
    for opening, closing in pairs:
        found_opposite = False
        direction = ""
        for k in range(opening + 1, closing):
            strong = _STRONG_OR_NUMBER.get(t[k])
            if strong == embedding:
                direction = embedding
                break
            if strong == opposite:
                found_opposite = True
        if not direction:
            if not found_opposite:
                continue
            context = sos
            for k in range(opening - 1, -1, -1):
                strong = _STRONG_OR_NUMBER.get(t[k])
                if strong:
                    context = strong
                    break
            direction = opposite if context == opposite else embedding
        for bracket in (opening, closing):
            t[bracket] = direction
            # Marks that followed the bracket follow its new direction.
            k = bracket + 1
            while k < len(t) and original[chars[k]] == "NSM":
                t[k] = direction
                k += 1


def _reset_whitespace(
    original: Sequence[str], levels: list[int], para_level: int
) -> None:
    """Rule L1, on the original classes, for a paragraph that is one line."""
    n = len(original)
    separators = (
        [i for i, cls in enumerate(original) if cls in {"S", "B"}]
        if "S" in original or "B" in original
        else []
    )
    for end in (*separators, n):
        if end < n:
            levels[end] = para_level
        k = end - 1
        while k >= 0 and original[k] in _TRAILING_RESET:
            levels[k] = para_level
            k -= 1


def reorder(levels: Sequence[int]) -> list[int]:
    """Rule L2: the indices of a line's characters in visual order."""
    order = list(range(len(levels)))
    if not levels:
        return order
    highest = max(levels)
    lowest_odd = min(levels) | 1
    for current in range(highest, lowest_odd - 1, -1):
        k = 0
        n = len(order)
        while k < n:
            if levels[order[k]] < current:
                k += 1
                continue
            end = k
            while end < n and levels[order[end]] >= current:
                end += 1
            order[k:end] = order[k:end][::-1]
            k = end
    return order
